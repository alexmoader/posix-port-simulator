#ifndef RESOURCES_H
#define RESOURCES_H

#include "port_types.h"

// В данном модуле реализованы утилиты работы с ресурсами порта:
// поиск свободных, занятие, освобождение.
//
// Модуль НЕ принимает решений - он только выполняет операции,
// которые ему поручает диспетчер.
//
// Все функции поиска возвращают ID ресурса или -1, если подходящего
// свободного нет. ID = индекс в массиве Port.<ресурсы>.
// Занятие причала, буксира и крана возвращает 1 при успехе, иначе 0.
// Учет склада возвращает фактически добавленный или убранный объем.
// Счетчики ресурсов в Port должны быть заполнены через config.
// Совместимость проверяет диспетчер через функции поиска.
// Записи ресурсов у судна диспетчер обновляет после успешного занятия.

//============================================
// ПОИСК СВОБОДНЫХ РЕСУРСОВ
//============================================

// находит первый свободный причал, совместимый с типом судна
// возвращает id причала или -1
int findFreeBerthForShip(const Port *port, ShipType shipType);

// находит первый свободный буксир, совместимый с типом судна
int findFreeTugForShip(const Port *port, ShipType shipType);

// находит первый свободный кран, совместимый с типом груза
int findFreeCraneForCargo(const Port *port, CargoType cargoType);

// находит склад, который:
//   1) совместим с типом груза
//   2) имеет достаточно свободного места для указанного объема
// возвращает id склада или -1
// volume - положительный объем порции, а не обязательно всего груза
int findWarehouseForCargo(const Port *port, CargoType cargoType, double volume);

//============================================
// ЗАНЯТИЕ РЕСУРСОВ
//============================================

// занимает причал судном (occupiedByShip = shipId)
// уже занятый ресурс не перезаписывается
int occupyBerth(Port *port, int berthId, int shipId);

// занимает буксир под конкретную миссию (busyWithShip = shipId, mission = ...)
int occupyTug(Port *port, int tugId, int shipId, TugMission mission);

// занимает кран судном (busyWithShip = shipId)
int occupyCrane(Port *port, int craneId, int shipId);

//"занимает" место на складе: currentLoad += volume
// если места мало, принимает только ту часть, которая помещается
// возвращает принятый объем, при ошибке или полном складе - 0
double occupyWarehouse(Port *port, int warehouseId, double volume);

//============================================
// ОСВОБОЖДЕНИЕ РЕСУРСОВ
//============================================

// при отдельном освобождении диспетчер проверяет владельца ресурса
// и освобождает соответствующую запись у судна

// освобождает причал (occupiedByShip = -1)
void releaseBerth(Port *port, int berthId);

// освобождает буксир (busyWithShip = -1, mission = TUG_FREE)
void releaseTug(Port *port, int tugId);

// освобождает кран (busyWithShip = -1)
void releaseCrane(Port *port, int craneId);

// освобождает место на складе: currentLoad -= volume
// используется при вывозе груза, возвращает фактически убранный объем
double releaseWarehouse(Port *port, int warehouseId, double volume);

//============================================
// КОМПЛЕКСНОЕ ОСВОБОЖДЕНИЕ
//============================================

// освобождает причалы, буксиры и краны, занятые данным судном
// вызывается после выхода из порта или при аварийном завершении
// сбрасывает записи ресурсов у судна, но груз на складе остается
// cargoProcessed не сбрасывается, это результат обработки судна
void releaseAllShipResources(Port *port, Ship *ship);

#endif // RESOURCES_H
