#ifndef CONFIG_H
#define CONFIG_H

#include "port_types.h"

// В данном модуле содержатся настройки и инициализации модели.

// Отвечает за:
//  - заполнение Port значениями по умолчанию;
//  - создание ресурсов (причалов, буксиров, кранов, складов);
//  - генерацию демонстрационного набора судов;
//  - разбор аргументов командной строки;
//  - печать текущей конфигурации.

//============================================
// ИНИЦИАЛИЗАЦИЯ
//============================================

// обнуляет порт и заполняет его настройками модели по умолчанию (без ресурсов)
void initPort(Port *port);

/*разбор аргументов командной строки и заполнение Port
 1) 0: успех, продолжать работу
 2) 1: была запрошена справка, завершить работу
 3) -1: ошибка, завершить работу*/
int parseArgs(int argc, char **argv, Port *port);

//============================================
// СОЗДАНИЕ ОТДЕЛЬНЫХ РЕСУРСОВ
//============================================

// Создает причал с заданной совместимостью с типами судов
void createBerth(Port *port, const int *compatibleShipFlags);

// создает буксир с заданной совместимостью с типами судов
void createTug(Port *port, const int *compatibleShipFlags);

// создает кран с заданной производительностью и совместимостью с типами грузов
void createCrane(Port *port, const int *compatibleCargoFlags, double productivity);

// создает склад с заданной вместимостью и совместимостью с типами грузов
void createWarehouse(Port *port, double capacity, const int *compatibleCargoFlags);

//============================================
// СОЗДАНИЕ НАБОРОВ РЕСУРСОВ ПО УМОЛЧАНИЮ
//============================================

// создает 4 причала с предустановленными матрицами совместимости
void createDefaultBerths(Port *port);

// создает 2 универсальных буксира
void createDefaultTugs(Port *port);

// создает 5 кранов, включая второй кран для навалочного груза
void createDefaultCranes(Port *port);

// создает 3 склада с разной специализацией
void createDefaultWarehouses(Port *port);

// вызывает все createDefault* последовательно
void createDefaultResources(Port *port);

//============================================
// ГЕНЕРАЦИЯ СУДОВ
//============================================

// генерирует демонстрационный набор судов, случайные типы, грузы и времена прибытия [0, timelimit]
void generateDemoShips(Port *port);

//============================================
// ПЕЧАТЬ КОНФИГУРАЦИИ
//============================================

// печатает текущую конфигурацию порта (для отладки и отчета)
void printConfig(const Port *port);

#endif // CONFIG_H
