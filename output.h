#ifndef OUTPUT_H
#define OUTPUT_H

#include "port_types.h"

// В данном модуле реализован вывод событий модели.
//
// Отвечает за:
//  - печать событий в терминал (с временем и категорией);
//  - запись тех же событий в лог-файл;
//  - перевод enum-значений в читаемые строки;
//  - печать итоговой статистики.

//============================================
// ИНИЦИАЛИЗАЦИЯ И ЗАКРЫТИЕ ЛОГА
//============================================

// открывает лог-файл перед запуском участников модели
// filename - путь к файлу (например "port.log")
void initLog(const char *filename);
// Подключает независимый процесс к журналу без удаления предыдущих событий.
void initWorkerLog(const char *filename);

// закрывает лог-файл, вызывается в конце main()
void closeLog(void);

//============================================
// ВЫВОД СОБЫТИЙ
//============================================

// печатает событие в терминал И в лог (если он открыт)
// поддерживает формат printf: logEvent(port, "Судно %d прибыло", id)
// автоматически добавляет префикс с текущим модельным временем
void logEvent(const Port *port, const char *format, ...);

//============================================
// ПЕРЕВОД ENUM -> СТРОКА
//============================================

// возвращает название типа судна
//(например SHIP_TANKER -> "танкер")
const char *shipTypeName(ShipType type);

// возвращает название типа груза
//(например CARGO_LIQUID -> "наливной")
const char *cargoTypeName(CargoType type);

// возвращает название стадии судна
//(например SHIP_ARRIVED -> "прибыло")
const char *shipStateName(ShipState state);

//============================================
// ИТОГОВАЯ СТАТИСТИКА
//============================================

// печатает финальную статистику модели:
//   - сколько судов обработано
//   - сколько осталось в ожидании
//   - сколько раз освободили кран при ожидании склада
//   - состояние и обработанный объем каждого судна
void printStatistics(const Port *port);

#endif // OUTPUT_H
